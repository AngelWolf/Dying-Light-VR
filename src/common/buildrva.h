// Which store's build of the engine / gamedll is loaded, and the rva a site has in it.
//
// Every fixed rva in this mod was read from the STEAM binaries (engine e9fbfc2c, gamedll 97046bba). The Epic (EGL)
// build is a separate compile of the same version: the same code, at shifted rvas, so on EGL every fixed-rva site
// refuses its own byte / slot / export check and the feature is off (read 2026-10-18, a tester's EGL dlls and run,
// ghidra-project/egl_engine/FINDINGS_2026-10-18.md).
//
// Rva() keeps the Steam value for Steam and for any build it does not know, so neither can change behaviour. On EGL
// it returns the EGL rva for the ALLOWLISTED sites in buildrva_table.h (generated by tools/egl_rva_table.py, which
// refuses any entry it cannot translate exactly), and the Steam value for everything else - which then refuses
// exactly as before. The site's own check still runs on the translated address: a wrong table entry refuses, it
// does not write.
//
// COST: the build is read once per module (PE header, two fields) and cached; a lookup is a binary search over a
// table of ~50 entries. Per-frame callers resolve into a static once.
#pragma once

#include <windows.h>

#include <cstdint>

#include "buildrva_table.h"

namespace dlvr {
namespace buildrva {

enum Module { kEngine = 0, kGamedll = 1 };
enum Build { kUnknown = 0, kSteam = 1, kEgl = 2, kNotLoaded = 3 };

// The link timestamp and image size of each known build, read from the files (tools/pecmp.py).
struct Known { DWORD stamp; DWORD image; Build build; };
constexpr Known kKnown[2][2] = {
    { { 0x6A4A8C7D, 0x0DFB000, kSteam }, { 0x6A4AA7A3, 0x0DF6000, kEgl } },    // engine_x64_rwdi.dll
    { { 0x6A4A8DD7, 0x1F64000, kSteam }, { 0x6A4AA921, 0x1F63000, kEgl } },    // gamedll_x64_rwdi.dll
};

inline const char* ModuleName(Module m)
{
    return m == kEngine ? "engine_x64_rwdi.dll" : "gamedll_x64_rwdi.dll";
}

inline const char* BuildName(Build b)
{
    return b == kSteam ? "STEAM" : b == kEgl ? "EGL" : b == kNotLoaded ? "not loaded" : "UNKNOWN";
}

// Cached per module once the module is mapped; "not loaded" is never cached, so an early caller retries.
inline Build ModuleBuild(Module m)
{
    static volatile LONG s_cached[2] = { -1, -1 };
    const LONG c = s_cached[m];
    if (c >= 0) {
        return static_cast<Build>(c);
    }
    HMODULE h = GetModuleHandleA(ModuleName(m));
    if (!h) {
        return kNotLoaded;
    }
    const auto base = reinterpret_cast<uintptr_t>(h);
    const auto* dos = reinterpret_cast<const IMAGE_DOS_HEADER*>(base);
    const auto* nt = reinterpret_cast<const IMAGE_NT_HEADERS64*>(base + dos->e_lfanew);
    Build b = kUnknown;
    for (const Known& k : kKnown[m]) {
        if (nt->FileHeader.TimeDateStamp == k.stamp && nt->OptionalHeader.SizeOfImage == k.image) {
            b = k.build;
        }
    }
    InterlockedExchange(&s_cached[m], static_cast<LONG>(b));
    return b;
}

// The rva `steamRva` has in the loaded build: the EGL value for an allowlisted site on EGL, otherwise `steamRva`.
inline uintptr_t Rva(Module m, uintptr_t steamRva)
{
    if (ModuleBuild(m) != kEgl) {
        return steamRva;
    }
    const RvaPair* t = m == kEngine ? kEglEngine : kEglGamedll;
    const size_t n = m == kEngine ? sizeof(kEglEngine) / sizeof(kEglEngine[0]) : sizeof(kEglGamedll) / sizeof(kEglGamedll[0]);
    size_t lo = 0;
    size_t hi = n;
    while (lo < hi) {
        const size_t mid = (lo + hi) / 2;
        if (t[mid].steam < steamRva) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    return (lo < n && t[lo].steam == steamRva) ? t[lo].egl : steamRva;
}

inline uintptr_t Eng(uintptr_t steamRva) { return Rva(kEngine, steamRva); }
inline uintptr_t Gd(uintptr_t steamRva) { return Rva(kGamedll, steamRva); }

// For the choke points that are handed an ABSOLUTE address (InstallDetour, the exec watches): if `abs` lies in the
// engine or gamedll image, translate its rva; anything else (rd3d11, filesystem - same code layout on EGL - our own
// memory) is returned unchanged. `moved` says whether it changed, for the caller's one-time log line.
inline uintptr_t Abs(uintptr_t abs, bool* moved = nullptr)
{
    if (moved) {
        *moved = false;
    }
    for (int i = 0; i < 2; ++i) {
        const Module m = static_cast<Module>(i);
        HMODULE h = GetModuleHandleA(ModuleName(m));
        if (!h) {
            continue;
        }
        const auto base = reinterpret_cast<uintptr_t>(h);
        const auto* dos = reinterpret_cast<const IMAGE_DOS_HEADER*>(base);
        const auto* nt = reinterpret_cast<const IMAGE_NT_HEADERS64*>(base + dos->e_lfanew);
        if (abs >= base && abs < base + nt->OptionalHeader.SizeOfImage) {
            const uintptr_t r = Rva(m, abs - base);
            if (moved) {
                *moved = r != abs - base;
            }
            return base + r;
        }
    }
    return abs;
}

}  // namespace buildrva
}  // namespace dlvr
