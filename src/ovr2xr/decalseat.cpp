// decalseat.cpp - DEV + BETA (ported 2026-11-07): seat decals onto the surface behind them. INV-695 (the measure), INV-696 (this).
// tools/decal_seat.py builds dlvr\decal_seat_<map>.bin from OUR map's .sobj: per decal with a CONFIDENT surface and a known front side, its instance
// index, old position (raw bits), front direction and gap to that surface. The game's files are NOT changed (a modified pak raises "modified game data", U-55).
// WHERE: entry of the engine's CSimpleObjects Initialize (+507660), called LAST by both loaders (Load +505A60 slot 40, +50D460 slot 44; dv24). At that
// point the 48-byte instance array (this+56, count this+64) is filled and not yet handed to any reader: +507660 copies the POINTER into its job blocks
// (es8), and every reader read so far builds its matrix from the live array (INV-687 (2), INV-688 (4), INV-694 (16)). So the move reaches drawing AND
// raytrace. NOT moved: the culling records (this+600) + the 4 trees, built by Load from the file: stale by the move (<= decal_seat_max_mm).
// WHAT MOVES (Jay 2026-11-06: 0.5 mm, 100 mm, sunk decals left alone): new = old - front * (gap - target), only when target < gap <= target + max.
// Every entry's old position must match the array or NOTHING in that file is changed. Per frame: NOTHING - the detour runs once per .sobj load.
