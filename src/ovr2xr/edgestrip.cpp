// edgestrip.cpp - DEV + BETA (ported 2026-11-07): slope the asphalt's edging strips (wl_asphalt_side_a) down into the ground, so they stop hovering where the road stands above the terrain. INV-694 (12), (13).
// tools/edge_strip.py builds dlvr\edge_strip_wasteland.bin from OUR wasteland_PC.rpack: offset + old + new value of each strip vertex's height in the pack's one vertex stream.
// The game's files are NOT changed (a modified pak raises "modified game data", U-55). On entry to the engine's RegisterBuffers (+406E00, per pack, CRLRPlatformPC::RegisterBuffers by the Mac 2022 names
// + the same 0xF0 / 0xF1 walk) the whole pack's vertex data is one block in memory, about to become ONE D3D buffer: the bytes are changed there, before the buffer exists.
// Every old value must match or nothing is changed. Shared meshes, so this applies to every placement of them, not only the farm. NOT changed: the asphalt, collision.
// Per frame: NOTHING. The detour runs once per pack load. At 0 it calls the original and returns.
